// Package completions generates the shell completion scripts hs ships and
// installs them where the shell reads them.
//
// # Generation
//
// The script is generated at runtime from the command table instead of being
// embedded as a file, so it cannot drift from the CLI: every command and every
// subcommand the table lists appears in the script, and a test reads that table
// to prove it. The dynamic completions are generated the same way: a session
// name comes from "hs session list --json" and a layout name from
// "hs space list --json", so the shell offers exactly the names the CLI
// resolves, project declarations included, instead of a second opinion.
//
// A failing herdr call must never print on the command line, so both reads drop
// stderr and a failed call simply yields no candidates. Fish calls them only
// while it is completing, so the CLI answering with an error never breaks a
// shell.
//
// # Install
//
// Fish reads completions from $XDG_CONFIG_HOME/fish/completions, or
// ~/.config/fish/completions when XDG_CONFIG_HOME is unset; FishDir resolves
// that directory and Install creates it, including every parent, and writes
// FileName into it. Nothing outside that directory is touched, and the
// completion runs straight from the CLI, so no other install step follows.
package completions

import (
	"errors"
	"fmt"
	"os"
	"path/filepath"
	"strings"
)

// FileName is the file fish reads the completions from.
const FileName = "hs.fish"

// Names is the kind of live name a command completes at its argument position.
// A command that takes neither completes no names at all.
type Names string

const (
	// NoNames is a command whose arguments are not drawn from the CLI.
	NoNames Names = ""
	// SessionNames completes herdr session names.
	SessionNames Names = "session"
	// LayoutNames completes stored layout names.
	LayoutNames Names = "layout"
)

// Command is one command of the CLI the shell completes: its name, the summary
// a completion menu shows, the subcommands it dispatches, and the live names its
// own arguments take.
type Command struct {
	Name     string
	Summary  string
	Children []Child
	Names    Names
}

// Child is one subcommand of a Command, with the same fields one level down.
type Child struct {
	Name    string
	Summary string
	Names   Names
}

// fishHeader defines the two name readers before anything uses them. Both parse
// the "name" field of the JSON the CLI prints, and both drop stderr so a herdr
// that is missing or failing produces no candidates and no noise.
const fishHeader = `# fish completions for hs. Generated by "hs completions fish"; regenerate with
# "hs completions fish --install" whenever hs changes.

function __hs_sessions
    command hs session list --json 2>/dev/null | string match -ra '"name": *"[^"]*"' | string replace -ra '^"name": *"' '' | string replace -ra '"$' ''
end

function __hs_layouts
    command hs space list --json 2>/dev/null | string match -ra '"name": *"[^"]*"' | string replace -ra '^"name": *"' '' | string replace -ra '"$' ''
end
`

// Fish renders the fish completion script for commands. The script completes the
// command tree statically and reads the session and layout names from the CLI on
// demand.
func Fish(commands []Command) string {
	var script strings.Builder
	script.WriteString(fishHeader)
	script.WriteString("\n")

	for _, command := range commands {
		fmt.Fprintf(&script, "complete -c hs -n '__fish_use_subcommand' -f -a %s -d %s\n",
			quote(command.Name), quote(command.Summary))
	}
	script.WriteString("\n")

	for _, command := range commands {
		writeChildren(&script, command)
	}

	for _, command := range commands {
		writeNames(&script, command)
	}
	return script.String()
}

// writeChildren completes the subcommands of one group, and stops offering files
// after a subcommand whose arguments are not paths.
func writeChildren(script *strings.Builder, command Command) {
	if len(command.Children) == 0 {
		return
	}
	siblings := make([]string, 0, len(command.Children))
	for _, child := range command.Children {
		siblings = append(siblings, child.Name)
	}
	for _, child := range command.Children {
		fmt.Fprintf(script, "complete -c hs -n '__fish_seen_subcommand_from %s; and not __fish_seen_subcommand_from %s' -f -a %s -d %s\n",
			command.Name, strings.Join(siblings, " "), quote(child.Name), quote(child.Summary))
		if child.Names == NoNames {
			fmt.Fprintf(script, "complete -c hs -n '__fish_seen_subcommand_from %s; and __fish_seen_subcommand_from %s' -f\n",
				command.Name, child.Name)
		}
	}
}

// writeNames completes the live names one command reads, at its own argument
// position or at the position of the subcommands that read the same kind.
func writeNames(script *strings.Builder, command Command) {
	if command.Names != NoNames {
		fmt.Fprintf(script, "complete -c hs -n '__fish_seen_subcommand_from %s'%s -a '(%s)'\n",
			command.Name, noFiles(command.Names), helper(command.Names))
		return
	}
	if len(command.Children) == 0 {
		fmt.Fprintf(script, "complete -c hs -n '__fish_seen_subcommand_from %s' -f\n", command.Name)
		return
	}

	for _, kind := range kinds(command.Children) {
		members := members(command.Children, kind)
		fmt.Fprintf(script, "complete -c hs -n '__fish_seen_subcommand_from %s; and __fish_seen_subcommand_from %s'%s -a '(%s)'\n",
			command.Name, strings.Join(members, " "), noFiles(kind), helper(kind))
	}
}

// kinds lists the name kinds a group's children use, in the order they declare
// them, so one completion line covers every child that reads that kind.
func kinds(children []Child) []Names {
	var found []Names
	for _, child := range children {
		if child.Names == NoNames {
			continue
		}
		known := false
		for _, kind := range found {
			if kind == child.Names {
				known = true
			}
		}
		if !known {
			found = append(found, child.Names)
		}
	}
	return found
}

// members lists the children that read one name kind.
func members(children []Child, kind Names) []string {
	var names []string
	for _, child := range children {
		if child.Names == kind {
			names = append(names, child.Name)
		}
	}
	return names
}

// helper is the fish function that reads one name kind from the CLI.
func helper(kind Names) string {
	if kind == LayoutNames {
		return "__hs_layouts"
	}
	return "__hs_sessions"
}

// noFiles turns file completion off for a name kind, except for layout names: a
// layout reference may be a path, so the shell keeps offering files there.
func noFiles(kind Names) string {
	if kind == LayoutNames {
		return ""
	}
	return " -f"
}

// quote wraps text in fish's single quotes, where a backslash escapes a quote.
func quote(text string) string {
	return "'" + strings.ReplaceAll(text, "'", `\'`) + "'"
}

// FishDir is the directory fish reads completions from:
// $XDG_CONFIG_HOME/fish/completions, or ~/.config/fish/completions when
// XDG_CONFIG_HOME is unset. It reports how to fix an environment that names
// neither instead of guessing a home directory.
func FishDir(getenv func(string) string) (string, error) {
	if base := getenv("XDG_CONFIG_HOME"); base != "" {
		return filepath.Join(base, "fish", "completions"), nil
	}
	home := getenv("HOME")
	if home == "" {
		return "", errors.New("cannot resolve the fish completion directory: export XDG_CONFIG_HOME or HOME, then run it again")
	}
	return filepath.Join(home, ".config", "fish", "completions"), nil
}

// Install writes the generated script into the fish completion directory,
// creating the directory and its parents when they do not exist, and returns the
// path it wrote.
func Install(commands []Command, getenv func(string) string) (string, error) {
	dir, err := FishDir(getenv)
	if err != nil {
		return "", err
	}
	if err := os.MkdirAll(dir, 0o755); err != nil {
		return "", fmt.Errorf("create the fish completion directory: %w", err)
	}
	path := filepath.Join(dir, FileName)
	if err := os.WriteFile(path, []byte(Fish(commands)), 0o644); err != nil {
		return "", fmt.Errorf("write the completion script: %w", err)
	}
	return path, nil
}
